<?php

namespace App\Services\Evaluation;

use App\Enums\BloomLevel;
use App\Enums\DaveLevel;
use App\Enums\LearningStateValue;
use App\Enums\NextLearningActionType;

/**
 * Independently authored library of synthetic NEXUS evaluation scenarios (M6-01).
 *
 * INDEPENDENCE BOUNDARY:
 * This class deliberately depends only on domain enums and the evaluation value
 * objects. It does NOT reference LearningStateInferenceService,
 * AdaptiveInterventionService, NextLearningActionService, NexusClosedLoopService,
 * or EvidenceValidationService. Every ExpectedOutcome below is hand-authored from
 * the scenario's intent, never generated by executing the rule under test. This is
 * what makes Expected independent of Actual.
 *
 * All data is synthetic. No real learner data is referenced.
 */
final class ScenarioLibrary
{
    private const CONCEPT = 'loops';

    /**
     * @return list<EvaluationScenario>
     */
    public function all(): array
    {
        $scenarios = [
            $this->stablePass(),
            $this->needsSupportRemedialPass(),
            $this->progressingClosedLoopPass(),
            $this->insufficientEvidenceBoundaryPass(),
            $this->uncertainOnlyReview(),
            $this->divergenceDetectionFail(),
        ];

        // Deterministic ordering by scenario_id.
        usort($scenarios, fn (EvaluationScenario $a, EvaluationScenario $b): int => strcmp($a->scenarioId, $b->scenarioId));

        return $scenarios;
    }

    /**
     * Learning State — stable: a single accepted submission should read as stable
     * task performance and continue, with no remedial intervention.
     */
    private function stablePass(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'LS-STABLE-001',
            category: 'learning_state',
            description: 'Single accepted submission on a first attempt.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [
                ['type' => 'submission_accepted', 'payload' => ['status' => 'success', 'passes_evaluation' => true]],
            ],
            runRetry: false,
            retryEvents: [],
            retryOutcome: null,
            expected: new ExpectedOutcome(
                state: LearningStateValue::Stable,
                nextAction: NextLearningActionType::Continue,
                expectRemedialIntervention: false,
                rationale: 'An accepted first attempt is a successful outcome; the learner should continue without remedial support.',
            ),
        );
    }

    /**
     * Intervention — needs_support: two rejected submissions with no acceptance
     * should create a remedial intervention and steer toward a guided retry.
     */
    private function needsSupportRemedialPass(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'IV-NEEDS-SUPPORT-001',
            category: 'intervention',
            description: 'Two rejected submissions, no acceptance, no retry yet.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
            ],
            runRetry: false,
            retryEvents: [],
            retryOutcome: null,
            expected: new ExpectedOutcome(
                state: LearningStateValue::NeedsSupport,
                nextAction: NextLearningActionType::GuidedRetry,
                expectRemedialIntervention: true,
                acceptableNextActions: [
                    NextLearningActionType::GuidedRetry,
                    NextLearningActionType::PracticeAgain,
                ],
                rationale: 'Repeated unresolved failures warrant a remedial intervention and a guided retry to gather new evidence.',
            ),
        );
    }

    /**
     * Closed loop — progressing: needs_support, remedial intervention, then a
     * successful retry should read as progressing and continue.
     */
    private function progressingClosedLoopPass(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'CL-PROGRESSING-001',
            category: 'closed_loop',
            description: 'Two rejections then an accepted retry after intervention.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
            ],
            runRetry: true,
            retryEvents: [
                ['type' => 'submission_accepted', 'payload' => ['status' => 'success', 'passes_evaluation' => true]],
            ],
            retryOutcome: 'success',
            expected: new ExpectedOutcome(
                state: LearningStateValue::Progressing,
                nextAction: NextLearningActionType::Continue,
                expectRemedialIntervention: true,
                rationale: 'A failure pattern corrected by a later accepted submission is progressing; the loop should continue.',
            ),
        );
    }

    /**
     * Boundary — insufficient evidence: no observable events should read as
     * insufficient_evidence and collect more evidence, never fabricating a state.
     */
    private function insufficientEvidenceBoundaryPass(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'BD-INSUFFICIENT-001',
            category: 'boundary',
            description: 'No observable learning events at all.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [],
            runRetry: false,
            retryEvents: [],
            retryOutcome: null,
            expected: new ExpectedOutcome(
                state: LearningStateValue::InsufficientEvidence,
                nextAction: NextLearningActionType::CollectMoreEvidence,
                expectRemedialIntervention: false,
                rationale: 'With no evidence the only responsible outcome is to collect more before deciding.',
            ),
        );
    }

    /**
     * Boundary/ambiguous — uncertain-only: a single anomalous execution produces
     * only uncertain evidence. Authored as ambiguous so the framework flags REVIEW.
     */
    private function uncertainOnlyReview(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'BD-UNCERTAIN-ONLY-001',
            category: 'boundary',
            description: 'Single code run that times out (uncertain system evidence only).',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [
                ['type' => 'code_run', 'payload' => ['status' => 'timeout']],
            ],
            runRetry: false,
            retryEvents: [],
            retryOutcome: null,
            expected: new ExpectedOutcome(
                state: LearningStateValue::NeedsSupport,
                nextAction: NextLearningActionType::CollectMoreEvidence,
                expectRemedialIntervention: false,
                acceptableStates: [
                    LearningStateValue::NeedsSupport,
                    LearningStateValue::InsufficientEvidence,
                ],
                acceptableNextActions: [
                    NextLearningActionType::CollectMoreEvidence,
                    NextLearningActionType::PracticeAgain,
                ],
                ambiguous: true,
                rationale: 'A single timed-out run is genuinely ambiguous between needs_support and insufficient_evidence; a human should review.',
            ),
        );
    }

    /**
     * Divergence detection — FAIL: an independently authored (intentionally wrong)
     * expectation that the learner is stable, contradicted by a clear failure
     * pattern. The framework must surface this disagreement as FAIL.
     */
    private function divergenceDetectionFail(): EvaluationScenario
    {
        return new EvaluationScenario(
            scenarioId: 'LS-DIVERGENCE-FAIL-001',
            category: 'learning_state',
            description: 'Two rejections, but the authored expectation asserts stable/continue.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            initialEvents: [
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
                ['type' => 'submission_rejected', 'payload' => ['status' => 'success', 'passes_evaluation' => false]],
            ],
            runRetry: false,
            retryEvents: [],
            retryOutcome: null,
            expected: new ExpectedOutcome(
                state: LearningStateValue::Stable,
                nextAction: NextLearningActionType::Continue,
                expectRemedialIntervention: false,
                rationale: 'Intentionally divergent expectation used to prove the evaluator detects and reports FAIL when NEXUS disagrees with an independent expectation.',
            ),
        );
    }
}
