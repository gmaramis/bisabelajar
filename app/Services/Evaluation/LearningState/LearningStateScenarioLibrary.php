<?php

namespace App\Services\Evaluation\LearningState;

use App\Enums\BloomLevel;
use App\Enums\DaveLevel;
use App\Enums\EvidenceCategory;
use App\Enums\EvidenceConfidence;
use App\Enums\EvidenceQuality;
use App\Enums\LearningStateValue;
use App\Enums\StateConfidence;

/**
 * Independently authored library of synthetic Learning State validation scenarios
 * (M6-02).
 *
 * INDEPENDENCE BOUNDARY:
 * This class depends only on domain enums and evaluation value objects. It does not
 * reference or execute any production inference/orchestration service. Every
 * ExpectedLearningState is hand-authored from the scenario's intent and the
 * documented M4-T03 behavior, never generated by running the rule under validation.
 * All data is synthetic; no real learner data is referenced.
 */
final class LearningStateScenarioLibrary
{
    private const CONCEPT = 'loops';

    /**
     * @return list<LearningStateScenario>
     */
    public function all(): array
    {
        $scenarios = [
            $this->stable(),
            $this->progressing(),
            $this->needsSupport(),
            $this->insufficientEmpty(),
            $this->insufficientUncertainOnly(),
            $this->lowConfidenceAmbiguous(),
            $this->evidenceQualityBoundary(),
            $this->divergenceFail(),
        ];

        usort($scenarios, fn (LearningStateScenario $a, LearningStateScenario $b): int => strcmp($a->scenarioId, $b->scenarioId));

        return $scenarios;
    }

    private function stable(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-STABLE-001',
            category: 'state_classification',
            description: 'Single accepted submission (valid, high confidence).',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_accepted', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::High),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::Stable,
                inferenceRule: 'stable_successful_outcome',
                cognitiveIndicator: 'successful_task_outcome_observed',
                psychomotorIndicator: 'successful_execution_observed',
                explanationContains: ['Learning State: stable.', 'Cognitive demand: apply.', 'Psychomotor demand: manipulation.'],
                expectedUsableCount: 1,
                expectedUncertainCount: 0,
                rationale: 'A single accepted submission is a successful outcome with no failure pattern → stable.',
            ),
        );
    }

    private function progressing(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-PROGRESSING-001',
            category: 'state_classification',
            description: 'A rejection followed by an accepted submission (recovery).',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_rejected', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::Medium),
                new EvidenceSpec('submission_accepted', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::High),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::Progressing,
                inferenceRule: 'progressing_corrective_success',
                cognitiveIndicator: 'corrective_application_observed',
                psychomotorIndicator: 'error_correction_then_successful_execution',
                requiredBehavioralIndicators: ['corrective_behavior'],
                explanationContains: ['Learning State: progressing.'],
                expectedUsableCount: 2,
                expectedUncertainCount: 0,
                rationale: 'A failure corrected by a later acceptance is corrective success → progressing.',
            ),
        );
    }

    private function needsSupport(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-NEEDS-SUPPORT-001',
            category: 'state_classification',
            description: 'A rejection plus a repeated-submission-failures behavioral signal.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_rejected', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::Medium),
                new EvidenceSpec('repeated_submission_failures', EvidenceCategory::Behavioral, EvidenceQuality::ContextDependent, EvidenceConfidence::Medium),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::NeedsSupport,
                inferenceRule: 'needs_support_repeated_failures',
                cognitiveIndicator: 'unresolved_performance_outcome_observed',
                requiredBehavioralIndicators: ['persistent_attempt_behavior'],
                explanationContains: ['Learning State: needs_support.', 'not an adaptive intervention'],
                expectedUsableCount: 2,
                expectedContextDependentCount: 1,
                rationale: 'Repeated unresolved failures without acceptance → needs_support (a state label, not an intervention).',
            ),
        );
    }

    private function insufficientEmpty(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-INSUFFICIENT-EMPTY-001',
            category: 'insufficient_evidence',
            description: 'No validated evidence at all.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [],
            expected: new ExpectedLearningState(
                state: LearningStateValue::InsufficientEvidence,
                inferenceRule: 'insufficient_evidence_minimal_usable',
                acceptableConfidences: [StateConfidence::High],
                explanationContains: ['Learning State: insufficient_evidence.', 'Uncertain evidence is not treated as valid support'],
                expectedUsableCount: 0,
                expectedUncertainCount: 0,
                rationale: 'With no evidence the only responsible outcome is insufficient_evidence at high state confidence.',
            ),
        );
    }

    private function insufficientUncertainOnly(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-INSUFFICIENT-UNCERTAIN-001',
            category: 'boundary',
            description: 'Only an uncertain system-context anomaly.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('execution_runtime_failure', EvidenceCategory::SystemContext, EvidenceQuality::Uncertain, EvidenceConfidence::Low),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::InsufficientEvidence,
                inferenceRule: 'insufficient_evidence_minimal_usable',
                explanationContains: ['Uncertain evidence is not treated as valid support'],
                expectedUsableCount: 0,
                expectedUncertainCount: 1,
                rationale: 'Uncertain-only system evidence is not usable support → insufficient_evidence.',
            ),
        );
    }

    private function lowConfidenceAmbiguous(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-LOWCONF-AMBIGUOUS-001',
            category: 'boundary',
            description: 'A single rejection with no acceptance and no repeated-failure signal.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_rejected', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::High),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::NeedsSupport,
                acceptableStates: [LearningStateValue::NeedsSupport, LearningStateValue::InsufficientEvidence],
                ambiguous: true,
                rationale: 'A lone rejection is genuinely ambiguous between needs_support and insufficient_evidence; a human should review.',
            ),
        );
    }

    private function evidenceQualityBoundary(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-QUALITY-BOUNDARY-001',
            category: 'evidence_quality',
            description: 'A single low-confidence performance rejection only.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_rejected', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::Low),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::InsufficientEvidence,
                inferenceRule: 'insufficient_evidence_minimal_usable',
                explanationContains: ['Learning State: insufficient_evidence.'],
                expectedUsableCount: 1,
                rationale: 'Low-confidence-only performance without acceptance or repeated failure is too weak → insufficient_evidence.',
            ),
        );
    }

    private function divergenceFail(): LearningStateScenario
    {
        return new LearningStateScenario(
            scenarioId: 'LSV-DIVERGENCE-FAIL-001',
            category: 'state_classification',
            description: 'An accepted submission, but the authored expectation asserts needs_support.',
            concept: self::CONCEPT,
            bloomDemand: BloomLevel::Apply,
            daveDemand: DaveLevel::Manipulation,
            evidence: [
                new EvidenceSpec('submission_accepted', EvidenceCategory::Performance, EvidenceQuality::Valid, EvidenceConfidence::High),
            ],
            expected: new ExpectedLearningState(
                state: LearningStateValue::NeedsSupport,
                rationale: 'Intentionally divergent expectation used to prove the validator detects and reports FAIL when the inference disagrees with an independent expectation.',
            ),
        );
    }
}
